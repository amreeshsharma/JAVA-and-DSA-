class Solution {
    public void calculate(int a, int b, int op) {
        // code here
        if(op==1){
            System.out.print(a+b);
        }else if(op==2){
            System.out.print(a-b);

        }else if(op==3){
            System.out.print(a*b);

        }else{
             System.out.print("Invalid Input");

        }
    }
}

